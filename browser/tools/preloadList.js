#!/usr/bin/env node
// The <link rel="modulepreload"> block in index.html, one per module of the static graph in breadth-first
// order, so an HTTP/2 load asks for the whole graph at once instead of discovering it a depth at a time.
//   node tools/preloadList.js --write   (rewrite the block)    node tools/preloadList.js --check
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, moduleGraph } from './graphManifest.js';

export const START = '<!-- modulepreload:start — generated by tools/preloadList.js, never edited by hand -->';
export const END = '<!-- modulepreload:end -->';
const INDEX = resolve(ROOT, 'index.html');

export const preloadBlock = (modules = moduleGraph().modules) =>
  [START, ...modules.map((m) => `  <link rel="modulepreload" href="${m}">`), `  ${END}`].join('\n');

// index.html with its block replaced, or with one inserted before </head> when it has none yet.
export const withBlock = (html, block = preloadBlock()) => {
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  if (a >= 0 && b > a) return html.slice(0, a) + block + html.slice(b + END.length);
  return html.replace('</head>', `  ${block}\n</head>`);
};

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const html = readFileSync(INDEX, 'utf8');
  const next = withBlock(html);
  if (process.argv[2] === '--write') {
    if (next !== html) writeFileSync(INDEX, next);
    console.log(`preloadList: ${moduleGraph().modules.length} modules${next === html ? ', unchanged' : ', written'}`);
  } else {
    console.log(`preloadList: ${next === html ? 'in step' : 'STALE — run node tools/preloadList.js --write'}`);
    process.exit(next === html ? 0 : 1);
  }
}
